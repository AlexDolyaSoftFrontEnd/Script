
// Переменные в JavaScript

// Переменная — это именованная область памяти, в которой хранится значение.
// В современном JavaScript используются `let` и `const`.


// Переменная объявлена с помощью let
// Значение можно изменить позже
let userName = 'Alex';

userName = 'Olexandr'; // допустимо


// Переменная объявлена с помощью const
// Значение нельзя переназначить
const siteVersion = '1.0.0';

// siteVersion = '1.0.1'; // ошибка


// Глобальные переменные

// Глобальная переменная объявляется вне функций и блоков.
// Она доступна из любого места скрипта.


// Глобальная переменная
let appStatus = 'active';

function checkStatus() {
  // Используем глобальную переменную внутри функции
  console.log('Статус приложения:', appStatus);
}

checkStatus();


// Комментарий:
// Глобальные переменные удобны, но опасны — любой код может их изменить.


// Локальные переменные

// Локальная переменная существует только внутри функции или блока `{}`.


function calculateTotal() {
  // Локальная переменная
  let price = 100;
  let tax = 20;

  // Возвращаем результат вычислений
  return price + tax;
}

console.log(calculateTotal());

// console.log(price); 
// ошибка — переменная недоступна

Комментарий:
// `price` и `tax` уничтожаются после завершения функции.


// Блочная область видимости

// Переменные `let` и `const` ограничены блоком `{}`.


if (true) {
  let message = 'Hello';
  const count = 3;

  // Внутри блока переменные доступны
  console.log(message, count);
}

// console.log(message); // ошибка

// Особенность var (почему его не используют)

// `var` не имеет блочной области видимости.

if (true) {
  var testValue = 10;
}

// Переменная доступна за пределами блока
console.log(testValue);


// Комментарий:
// Из-за такого поведения `var` приводит к ошибкам и считается устаревшим.


// Цикл for

// Используется, когда известно количество повторений.

// i — локальная переменная цикла
for (let i = 0; i < 5; i++) {
  // Код выполняется 5 раз
  console.log('Итерация:', i);
}

// console.log(i); // ошибка — i существует только внутри цикла

// Цикл while

// Выполняется, пока условие истинно.


let counter = 0;

// Проверка условия перед каждой итерацией
while (counter < 3) {
  console.log('Счётчик:', counter);

  // Изменяем значение, чтобы цикл завершился
  counter++;
}

// Комментарий:
// Если не менять `counter`, цикл станет бесконечным.

// Цикл do...while

// Гарантированно выполняется хотя бы один раз.

let value = 5;

do {
  console.log('Текущее значение:', value);
  value++;
} while (value < 3);
```

// Комментарий:
// Даже при ложном условии тело выполнится один раз.

// Перебор массива через for...of

// Используется для перебора значений массива.


const fruits = ['apple', 'banana', 'orange'];

for (const fruit of fruits) {
  // fruit — локальная переменная каждой итерации
  console.log(fruit);
}

// еребор массива через forEach

// Функциональный и часто используемый подход.


const numbers = [10, 20, 30];

numbers.forEach((number, index) => {
  // number и index — локальные параметры колбэка
  console.log('Индекс:', index, 'Значение:', number);
});
```
//  Вложенные области видимости


let globalValue = 1;

function outerFunction() {
  let outerValue = 2;

  function innerFunction() {
    let innerValue = 3;

    // Доступ ко всем внешним областям
    console.log(globalValue, outerValue, innerValue);
  }

  innerFunction();
}

outerFunction();


// Комментарий:
// Это пример цепочки областей видимости (scope chain).

//  Типичная ошибка с глобальной переменной


let total = 100;

function updateTotal() {
  // Изменяет глобальную переменную
  total = 200;
}

updateTotal();


// Правильный вариант:


function updateTotal() {
  // Локальная переменная, не влияет на глобальную
  let total = 200;
  return total;
}

// Общий вывод

// Локальные переменные безопаснее глобальных.
// `let` и `const` обеспечивают предсказуемую область видимости.
// Циклы создают собственный scope.
// Чёткое понимание областей видимости — основа стабильного JavaScript-кода.
