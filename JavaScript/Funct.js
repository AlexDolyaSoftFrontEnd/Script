/* ---------------------------------------------------------------------------
Модуль с инкапсулированным состоянием (замыкание)
--------------------------------------------------------------------------- */
/*
items — приватное состояние.
Доступ к нему возможен только через возвращаемые функции.
*/

function createCart() {
  let items = [];

  function addItem(product) {
    items.push(product);
  }

  function removeItem(id) {
    items = items.filter(item => item.id !== id);
  }

  function getTotal() {
    return items.reduce((sum, item) => sum + item.price, 0);
  }

  return { addItem, removeItem, getTotal };
}

/* ---------------------------------------------------------------------------
Функция-фабрика с приватной конфигурацией
--------------------------------------------------------------------------- */
/*
prefix сохраняется через замыкание.
Используется для логирования, конфигураций, API.
*/

function createLogger(prefix) {
  return function log(message) {
    console.log(`[${prefix}] ${message}`);
  };
}

/* ---------------------------------------------------------------------------
Композиция функций (pipe)
--------------------------------------------------------------------------- */
/*
Объединяет несколько функций в одну цепочку.
Данные проходят через функции слева направо.
*/

function pipe(...fns) {
  return value => fns.reduce((acc, fn) => fn(acc), value);
}

/* ---------------------------------------------------------------------------
Каррирование и валидация
--------------------------------------------------------------------------- */
/*
Функция возвращает специализированную функцию.
Используется для бизнес-правил и форм.
*/

function createValidator(rule) {
  return value => rule(value);
}

/* ---------------------------------------------------------------------------
Асинхронный контроллер состояния
--------------------------------------------------------------------------- */
/*
Оборачивает async-функцию и хранит состояние запроса.
Полезно для UI и API-слоёв.
*/

function createRequest(fn) {
  let loading = false;
  let error = null;

  async function run(...args) {
    loading = true;
    error = null;

    try {
      return await fn(...args);
    } catch (e) {
      error = e;
      throw e;
    } finally {
      loading = false;
    }
  }

  function getState() {
    return { loading, error };
  }

  return { run, getState };
}

/* ---------------------------------------------------------------------------
Reducer-функция
--------------------------------------------------------------------------- */
/*
Чистая функция управления состоянием.
Используется в React (useReducer, Redux).
*/

function todosReducer(state, action) {
  switch (action.type) {
    case "add":
      return [...state, action.payload];
    case "remove":
      return state.filter(todo => todo.id !== action.id);
    default:
      return state;
  }
}

/* ---------------------------------------------------------------------------
Иммутабельное обновление данных
--------------------------------------------------------------------------- */
/*
Возвращает новый массив и объекты,
не изменяя исходные данные.
*/

function updateUser(users, id, data) {
  return users.map(user =>
    user.id === id
      ? { ...user, profile: { ...user.profile, ...data } }
      : user
  );
}

/* ---------------------------------------------------------------------------
Мемоизация
--------------------------------------------------------------------------- */
/*
Кэширует результат функции.
Используется для оптимизации тяжёлых вычислений.
*/

function memoize(fn) {
  const cache = new Map();

  return function (...args) {
    const key = JSON.stringify(args);
    if (cache.has(key)) return cache.get(key);

    const result = fn(...args);
    cache.set(key, result);
    return result;
  };
}
