function say(city) {
  console.log(this.name, city);
}
say.call(user, "Kyiv");

/* ---------------------------------------------------------------------------
Параметры по умолчанию и rest-параметры
--------------------------------------------------------------------------- */
/*
Позволяют задавать значения по умолчанию
и принимать неограниченное количество аргументов.
*/

function sumAll(a = 0, ...nums) {
  return nums.reduce((x, y) => x + y, a);
}

/* ---------------------------------------------------------------------------
Замыкания
--------------------------------------------------------------------------- */
/*
Функция запоминает внешнее состояние даже после завершения
внешней функции. Используется для инкапсуляции данных.
*/

function counter() {
  let count = 0;
  return () => ++count;
}

